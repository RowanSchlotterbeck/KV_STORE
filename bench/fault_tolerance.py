class HarnessError(Exception):
    """The harness or cluster could not do what a run needs (not a finding)."""


class InvariantViolation(Exception):
    """A real finding: an acknowledged write lost, divergence, or a forbidden commit."""


# ---------------------------------------------------------------- ports, config

def free_ports(n):
    """n distinct ports the OS just handed out (bound to 0, then released)."""
    socks, ports = [], set()
    while len(ports) < n:
        s = socket.socket()
        s.bind((HOST, 0))
        socks.append(s)
        ports.add(s.getsockname()[1])
    for s in socks:
        s.close()
    return sorted(ports)


def election_timing(repo_root):
    """(min_ms, max_ms, heartbeat_ms) from include/raft_node.h, or None."""
    path = os.path.join(repo_root, "include", "raft_node.h")
    try:
        text = open(path).read()
    except OSError:
        return None
    vals = {}
    for name in ("kElectionTimeoutMin", "kElectionTimeoutMax", "kHeartbeatInterval"):
        m = re.search(name + r"\{(\d+)\}", text)
        if not m:
            return None
        vals[name] = int(m.group(1))
    return vals["kElectionTimeoutMin"], vals["kElectionTimeoutMax"], vals["kHeartbeatInterval"]


