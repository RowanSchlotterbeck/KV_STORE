def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("binary", help="path to kv_server")
    p.add_argument("part", nargs="?", choices=["all", "failover", "chaos"], default="all")
    p.add_argument("--nodes", type=int, default=3, help="cluster size (default 3; try 5)")
    p.add_argument("--trials", type=int, default=50, help="Part A failover trials (default 50)")
    p.add_argument("--chaos-seconds", type=float, default=60.0, help="Part B duration (default 60)")
    p.add_argument("--writers", type=int, default=2, help="Part B concurrent writers (default 2)")
    p.add_argument("--fault-min", type=float, default=0.3, help="shortest fault, seconds (default 0.3)")
    p.add_argument("--fault-max", type=float, default=3.0, help="longest fault, seconds (default 3)")
    p.add_argument("--no-minority-phase", dest="minority_phase", action="store_false",
                   help="skip the bounded phase that freezes a majority")
    p.add_argument("--minority-seconds", type=float, default=8.0,
                   help="majority-frozen phase length; keep it above --request-timeout so writes are "
                        "actually sent into it (default 8)")
    p.add_argument("--request-timeout", type=float, default=3.0,
                   help="client wait for a reply before calling a write ambiguous (default 3)")
    p.add_argument("--converge-timeout", type=float, default=180.0,
                   help="how long to wait for all nodes to agree after faults stop (default 180)")
    p.add_argument("--seed", type=int, default=None, help="chaos RNG seed (printed if not given)")
    p.add_argument("--quick", action="store_true", help="5 trials, 15s of chaos")
    p.add_argument("--keep", action="store_true", help="keep the temp dir even on success")
    p.add_argument("--verbose", action="store_true", help="print the chaos timeline")
    args = p.parse_args()
    if args.quick:
        args.trials, args.chaos_seconds = 5, 15.0
    if args.seed is None:
        args.seed = random.randrange(1 << 30)
    if args.nodes < 3:
        p.error("--nodes must be at least 3")
    binary = os.path.abspath(args.binary)
    if not os.access(binary, os.X_OK):
        p.error(f"{binary} is not an executable")

    Cluster.converge_timeout = args.converge_timeout
    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    timing = election_timing(repo_root)
    workdir = tempfile.mkdtemp(prefix="kv_fault_")
    clusters = []

    def cleanup():
        for c in clusters:
            c.kill_all()

    atexit.register(cleanup)
    for sig in (signal.SIGINT, signal.SIGTERM):
        signal.signal(sig, lambda s, f: (cleanup(), sys.exit(128 + s)))

    print(f"fault-tolerance benchmark: {binary}")
    print(f"  workdir {workdir}, seed {args.seed}"
          + (f", election timeout {timing[0]}-{timing[1]} ms, heartbeat {timing[2]} ms" if timing else ""))
    ok = False
    try:
        results = {}
        if args.part in ("all", "failover"):
            c = Cluster(binary, args.nodes, os.path.join(workdir, "failover"))
            clusters.append(c)
            try:
                results["failover"] = part_a(c, args, timing)
            finally:
                c.kill_all()
        if args.part in ("all", "chaos"):
            c = Cluster(binary, args.nodes, os.path.join(workdir, "chaos"))
            clusters.append(c)
            try:
                results["chaos"] = part_b(c, args)
            finally:
                c.kill_all()
        print("\nJSON " + json.dumps(results))
        ok = True
        return 0
    except InvariantViolation as e:
        print(f"\n!!! INVARIANT VIOLATED: {e}", file=sys.stderr)
        return 1
    except HarnessError as e:
        print(f"\n!!! harness error (not a correctness finding): {e}", file=sys.stderr)
        return 2
    finally:
        cleanup()
        if ok and not args.keep:
            shutil.rmtree(workdir, ignore_errors=True)
        else:
            print(f"  logs kept in {workdir}", file=sys.stderr if not ok else sys.stdout)


if __name__ == "__main__":
    sys.exit(main())
