#!/usr/bin/env python3
"""Fault-tolerance benchmark for a real kv_server Raft cluster.

Part A (failover): how long the cluster accepts no writes after its leader
is SIGKILLed, over many trials.

Part B (chaos): a Jepsen-style check that every ACKNOWLEDGED write survives
repeated crashes (SIGKILL + restart) and unreachable nodes (SIGSTOP +
SIGCONT), with no divergence between nodes.

    python3 -I bench/fault_tolerance.py build/kv_server [all|failover|chaos] [options]

Write outcomes are classified exactly; only OK counts as acknowledged:
  OK                                    -> ACKNOWLEDGED: must be present at the end
  REDIRECT <id> [<host>:<port>]         -> not an outcome: resend to that node
  ERR_NO_LEADER, connection refused     -> NOT acknowledged (never proposed): retry
  ERR_LEADERSHIP_LOST, ERR_TIMEOUT,
  connection dropped / no reply in time -> AMBIGUOUS: may or may not have committed;
                                           reported, never asserted either way

Reads are not linearizable at this version (a leader serves GET from its
applied state), so nothing is read back until chaos has stopped and every
node agrees on leader, term and commit index. Followers answer GET with
REDIRECT, so divergence is checked on the nodes' log files instead: the
committed prefix (1..commit_index) must be identical on every node.

SIGSTOP models an unreachable (partitioned) node without root or firewall
rules: the kernel still completes TCP handshakes, but the process reads and
answers nothing, so to its peers and clients it is silent. SIGCONT heals it
with its state intact.

Every node runs in a fresh temp dir with a generated config and ports the OS
handed out; every spawned node is SIGKILLed on exit, even on an exception.
The temp dir is removed on success and kept (path printed) on failure.
"""

