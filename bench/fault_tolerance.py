@dataclass
class Node:
    id: int
    peer_port: int
    client_port: int
    status_port: int
    log_path: str
    out_path: str
    err_path: str
    proc: subprocess.Popen = None
    frozen: bool = False
    starts: int = 0


class Cluster:
    """N kv_server processes on loopback, each with its own log in `workdir`."""

    def __init__(self, binary, n, workdir):
        self.binary = binary
        self.workdir = workdir
        self.lock = threading.RLock()  # guards process state (chaos vs. main thread)
        ports = free_ports(3 * n)
        self.nodes = {}
        conf_lines = ["# generated by bench/fault_tolerance.py: <node_id> <host> <peer_port>"]
        for i in range(n):
            nid = i + 1
            node_dir = os.path.join(workdir, f"n{nid}")
            os.makedirs(node_dir)
            self.nodes[nid] = Node(nid, ports[3 * i], ports[3 * i + 1], ports[3 * i + 2],
                                   os.path.join(node_dir, "kv.log"),
                                   os.path.join(node_dir, "stdout.txt"),
                                   os.path.join(node_dir, "stderr.txt"))
            conf_lines.append(f"{nid} {HOST} {ports[3 * i]}")
        self.config = os.path.join(workdir, "cluster.conf")
        with open(self.config, "w") as f:
            f.write("\n".join(conf_lines) + "\n")
        self.port_to_id = {node.client_port: nid for nid, node in self.nodes.items()}

    @property
    def size(self):
        return len(self.nodes)

    def majority(self):
        return self.size // 2 + 1

    def start(self, nid):
        with self.lock:
            node = self.nodes[nid]
            if node.proc and node.proc.poll() is None:
                raise HarnessError(f"node {nid} already running")
            args = [self.binary, node.log_path, "--cluster", self.config, "--node-id", str(nid),
                    "--client-port", str(node.client_port), "--status-port", str(node.status_port)]
            # Append across restarts so a node's whole history stays in one file.
            out = open(node.out_path, "a")
            err = open(node.err_path, "a")
            node.proc = subprocess.Popen(args, stdout=out, stderr=err, stdin=subprocess.DEVNULL)
            out.close()
            err.close()
            node.frozen = False
            node.starts += 1

    def start_all(self):
        for nid in self.nodes:
            self.start(nid)

    def kill(self, nid):
        with self.lock:
            node = self.nodes[nid]
            if node.proc and node.proc.poll() is None:
                node.proc.kill()  # SIGKILL, works on a stopped process too
                node.proc.wait()
            node.frozen = False

    def freeze(self, nid):
        with self.lock:
            node = self.nodes[nid]
            if node.proc and node.proc.poll() is None:
                os.kill(node.proc.pid, signal.SIGSTOP)
                node.frozen = True

    def thaw(self, nid):
        with self.lock:
            node = self.nodes[nid]
            if node.proc and node.proc.poll() is None and node.frozen:
                os.kill(node.proc.pid, signal.SIGCONT)
            node.frozen = False

    def running(self, nid):
        node = self.nodes[nid]
        return node.proc is not None and node.proc.poll() is None

    def healthy(self, nid):
        return self.running(nid) and not self.nodes[nid].frozen

    def kill_all(self):
        with self.lock:
            for nid in self.nodes:
                try:
                    self.kill(nid)
                except Exception:
                    pass

    def unexpected_exits(self):
        """Nodes that died on their own (not by our SIGKILL): a crash is a finding."""
        out = []
        for nid, node in self.nodes.items():
            if node.proc and node.proc.poll() is not None and node.proc.returncode not in (-signal.SIGKILL,):
                out.append((nid, node.proc.returncode))
        return out

    # ---- /status

    def status(self, nid, timeout=0.3):
        node = self.nodes[nid]
        try:
            with urllib.request.urlopen(f"http://{HOST}:{node.status_port}/status", timeout=timeout) as r:
                return json.loads(r.read())
        except Exception:
            return None

    def statuses(self, nids=None):
        return {nid: self.status(nid) for nid in (nids or self.nodes)}

    def agreed_leader(self, nids):
        """(leader, term) if every node in nids answers and they agree on one leader."""
        sts = self.statuses(nids)
        if any(s is None for s in sts.values()):
            return None
        leaders = {s["leader_id"] for s in sts.values()}
        terms = {s["current_term"] for s in sts.values()}
        roles = [nid for nid, s in sts.items() if s["role"] == "leader"]
        if len(leaders) != 1 or len(terms) != 1 or len(roles) != 1 or roles[0] not in leaders:
            return None
        return roles[0], terms.pop()

    def await_stable_leader(self, nids, hold=0.5, deadline=15.0):
        """Waits until nids agree on one leader and term for `hold` seconds."""
        start = time.monotonic()
        since, current = None, None
        while time.monotonic() - start < deadline:
            got = self.agreed_leader(nids)
            if got != current:
                current, since = got, time.monotonic()
            elif got is not None and time.monotonic() - since >= hold:
                return got
            time.sleep(0.05)
        raise HarnessError(f"no stable leader among nodes {sorted(nids)} within {deadline}s "
                           f"(last statuses: {self.statuses(nids)})")

    converge_timeout = 180.0  # set from --converge-timeout
    last_converge_seconds = 0.0

    def await_converged(self, deadline=None):
        """Waits until every node is up and they agree on leader, term and a
        commit index that is fully applied and equals the leader's last index,
        twice in a row. Returns (leader, term, commit_index). A follower that
        fell far behind catches up one log index per heartbeat until it finds
        the point where its log matches the leader's, so this can take a while
        after heavy chaos; the time taken is kept in last_converge_seconds."""
        deadline = deadline or self.converge_timeout
        start = time.monotonic()
        previous = None
        last = None
        while time.monotonic() - start < deadline:
            sts = self.statuses()
            last = sts
            ok = all(s is not None for s in sts.values())
            if ok:
                leaders = [nid for nid, s in sts.items() if s["role"] == "leader"]
                key = ({s["leader_id"] for s in sts.values()}, {s["current_term"] for s in sts.values()},
                       {s["commit_index"] for s in sts.values()}, {s["last_applied"] for s in sts.values()})
                ok = (len(leaders) == 1 and all(len(k) == 1 for k in key)
                      and key[0] == {leaders[0]}
                      and key[2] == key[3]
                      and sts[leaders[0]]["log_last_index"] == next(iter(key[2])))
                if ok:
                    snapshot = (leaders[0], next(iter(key[1])), next(iter(key[2])))
                    if snapshot == previous:
                        self.last_converge_seconds = time.monotonic() - start
                        return snapshot
                    previous = snapshot
                    time.sleep(0.3)
                    continue
            previous = None
            time.sleep(0.1)
        raise HarnessError(f"cluster did not converge within {deadline}s; last statuses: {last}")


# ---------------------------------------------------------------- client

def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


@dataclass
class WriteRecord:
    key: str
    value: str
    outcome: str        # "ack" | "ambiguous"
    sent_at: float      # monotonic, when the request that produced the outcome was sent
    done_at: float      # monotonic, when the outcome was known
    detail: str = ""


class ProtocolError(Exception):
    pass


class LineClient:
    """One TCP connection speaking the line protocol, retargetable by node id."""

    def __init__(self, cluster, timeout):
        self.cluster = cluster
        self.timeout = timeout
        self.sock = None
        self.buf = b""
        self.node = None

    def close(self):
        if self.sock:
            try:
                self.sock.close()
            except OSError:
                pass
        self.sock, self.buf, self.node = None, b"", None

    def connect(self, nid):
        self.close()
        s = socket.create_connection((HOST, self.cluster.nodes[nid].client_port), timeout=self.timeout)
        s.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
        s.settimeout(self.timeout)
        self.sock, self.node = s, nid

    def request(self, line):
        """Sends one line, returns the reply line. Raises OSError/socket.timeout
        on a dropped or silent connection."""
        self.sock.sendall(line.encode() + b"\n")
        while b"\n" not in self.buf:
            chunk = self.sock.recv(4096)
            if not chunk:
                raise ConnectionResetError("server closed the connection")
            self.buf += chunk
        reply, self.buf = self.buf.split(b"\n", 1)
        return reply.decode()


def redirect_target(cluster, reply):
    """Node id a REDIRECT reply names (by id, or by its host:port if given)."""
    parts = reply.split()
    if len(parts) >= 3 and ":" in parts[2]:
        port = int(parts[2].rsplit(":", 1)[1])
        if port in cluster.port_to_id:
            return cluster.port_to_id[port]
    nid = int(parts[1])
    if nid not in cluster.nodes:
        raise ProtocolError(f"REDIRECT to unknown node: {reply!r}")
    return nid


class Writer:
    """Sequential unique-key PUTs, each driven to a definitive outcome
    (acknowledged or ambiguous). Not-acknowledged answers are retried with
    the same key and value, so a key is never left in an unknown state
    without being recorded as ambiguous."""

    def __init__(self, cluster, prefix, timeout, retry_delay=0.01):
        self.cluster = cluster
        self.prefix = prefix
        self.client = LineClient(cluster, timeout)
        self.retry_delay = retry_delay
        self.records = []
        self.attempts = 0       # requests sent
        self.not_acked = 0      # ERR_NO_LEADER / refused answers (retried)
        self.redirects = 0
        self.unexpected = []    # replies outside the protocol: a finding
        self.seq = 0
        self.stop = threading.Event()
        self._rr = 0

    def _next_target(self):
        ids = sorted(self.cluster.nodes)
        self._rr = (self._rr + 1) % len(ids)
        return ids[self._rr]

    def write_one(self):
        key = f"{self.prefix}{self.seq}"
        value = f"v{self.seq}-{random.getrandbits(32):08x}"
        self.seq += 1
        line = f"PUT {quote(key)} {quote(value)}"
        target = self.client.node or self._next_target()
        hops = 0
        while not self.stop.is_set():
            if self.client.node != target:
                try:
                    self.client.connect(target)
                except OSError:
                    # Refused (node down) or no handshake: never sent, so not acknowledged.
                    self.not_acked += 1
                    target = self._next_target()
                    time.sleep(self.retry_delay)
                    continue
            sent = time.monotonic()
            self.attempts += 1
            try:
                reply = self.client.request(line)
            except (OSError, socket.timeout) as e:
                # Sent, and then the connection dropped or went silent: it may
                # have been proposed and committed.
                rec = WriteRecord(key, value, "ambiguous", sent, time.monotonic(), f"{type(e).__name__}: {e}")
                self.client.close()
                self.records.append(rec)
                return rec
            now = time.monotonic()
            if reply == "OK":
                rec = WriteRecord(key, value, "ack", sent, now, f"node {self.client.node}")
                self.records.append(rec)
                return rec
            if reply.startswith("REDIRECT "):
                self.redirects += 1
                hops += 1
                target = redirect_target(self.cluster, reply)
                if hops > 2 * self.cluster.size:
                    hops = 0
                    time.sleep(self.retry_delay)  # stale hints bouncing around: let the election settle
                continue
            if reply == "ERR_NO_LEADER":
                self.not_acked += 1
                target = self._next_target()
                time.sleep(self.retry_delay)
                continue
            if reply in ("ERR_LEADERSHIP_LOST", "ERR_TIMEOUT"):
                rec = WriteRecord(key, value, "ambiguous", sent, now, reply)
                self.records.append(rec)
                return rec
            self.unexpected.append((key, value, reply))
            raise ProtocolError(f"unexpected reply to {line!r}: {reply!r}")
        # Stopped while still trying: never sent anything that could commit
        # since the last definitive answer, so this key is simply unused.
        self.seq -= 1
        return None

    def run(self):
        try:
            while not self.stop.is_set():
                self.write_one()
        finally:
            self.client.close()

    def acked(self):
        return [r for r in self.records if r.outcome == "ack"]

    def ambiguous(self):
        return [r for r in self.records if r.outcome == "ambiguous"]


# ---------------------------------------------------------------- log files

def varint(buf, i):
    shift = result = 0
    while True:
        b = buf[i]
        i += 1
        result |= (b & 0x7F) << shift
        if not b & 0x80:
            return result, i
        shift += 7


def parse_fields(buf):
    """{field_number: [values]} for a protobuf message (varint and length-delimited only)."""
    out, i = {}, 0
    while i < len(buf):
        tag, i = varint(buf, i)
        num, wt = tag >> 3, tag & 7
        if wt == 0:
            v, i = varint(buf, i)
        elif wt == 2:
            n, i = varint(buf, i)
            v, i = bytes(buf[i:i + n]), i + n
        else:
            raise ValueError(f"unexpected wire type {wt}")
        out.setdefault(num, []).append(v)
    return out


def read_log(path):
    """Entries of a PersistentLog file as (index, term, operation, key, value|None).
    Frame: u32 LE payload length, u32 LE CRC32C, payload = kvstore.LogEntry."""
    data = open(path, "rb").read()
    entries, off = [], 0
    while off + 8 <= len(data):
        (length,) = struct.unpack_from("<I", data, off)
        if length == 0 or off + 8 + length > len(data):
            break  # zeroed or torn tail: replay would cut it off too
        f = parse_fields(data[off + 8: off + 8 + length])
        cmd = parse_fields(f.get(3, [b""])[0])
        entries.append((f.get(1, [0])[0], f.get(2, [0])[0],
                        cmd.get(1, [b""])[0].decode(), cmd.get(2, [b""])[0].decode("utf-8", "replace"),
                        cmd[3][0].decode("utf-8", "replace") if 3 in cmd else None))
        off += 8 + length
    return entries


def fold(entries):
    """The store a sequence of committed entries produces."""
    store = {}
    for _, _, op, key, value in entries:
        if op == "PUT":
            store[key] = value if value is not None else ""
        elif op == "DEL":
            store.pop(key, None)
    return store


# ---------------------------------------------------------------- verification

def verify(cluster, writers, label):
    """After convergence: every acknowledged write is readable via the leader
    with its value, the committed log prefix is identical on every node, and
    the committed state holds no write the harness never sent. Returns a dict
    of counts; raises InvariantViolation on any lost write or divergence."""
    leader, term, commit = cluster.await_converged()
    acked = [r for w in writers for r in w.acked()]
    ambiguous = [r for w in writers for r in w.ambiguous()]
    sent_values = {r.key: r.value for w in writers for r in w.records}

    # 1. Read back every acknowledged write from the leader.
    client = LineClient(cluster, timeout=5.0)
    client.connect(leader)
    lost = []
    for r in acked:
        got = client.request(f"GET {quote(r.key)}")
        if got != r.value:
            lost.append((r.key, r.value, got))
    amb_present = sum(1 for r in ambiguous if client.request(f"GET {quote(r.key)}") == r.value)
    client.close()

    # 2. Committed prefixes identical on every node (nodes are quiescent now).
    logs = {nid: read_log(node.log_path) for nid, node in cluster.nodes.items()}
    short = {nid: len(e) for nid, e in logs.items() if len(e) < commit}
    divergent = []
    if not short:
        ref = logs[leader][:commit]
        for nid, entries in logs.items():
            if entries[:commit] != ref:
                first = next(i for i, (a, b) in enumerate(zip(entries[:commit], ref)) if a != b)
                divergent.append((nid, first + 1, entries[first], ref[first]))

    # 3. The committed state agrees with what the clients were told.
    state = fold(logs[leader][:commit])
    phantom = [k for k in state if k not in sent_values]
    state_lost = [(r.key, r.value, state.get(r.key)) for r in acked if state.get(r.key) != r.value]

    result = {"leader": leader, "term": term, "commit_index": commit,
              "converge_seconds": cluster.last_converge_seconds, "acknowledged": len(acked),
              "ambiguous": len(ambiguous), "ambiguous_present": amb_present,
              "lost": len(lost), "divergent_nodes": len(divergent) + len(short)}
    problems = []
    if lost:
        problems.append(f"{len(lost)} acknowledged write(s) not readable correctly via leader {leader}: "
                        + "; ".join(f"{k}={v!r} read back {g!r}" for k, v, g in lost[:20]))
    if state_lost:
        problems.append(f"{len(state_lost)} acknowledged write(s) wrong/missing in the committed log: "
                        + "; ".join(f"{k}={v!r} committed state {g!r}" for k, v, g in state_lost[:20]))
    if short:
        problems.append(f"node log(s) shorter than commit index {commit}: {short}")
    for nid, idx, mine, ref in divergent:
        problems.append(f"node {nid} diverges from leader {leader} at committed index {idx}: "
                        f"{mine} vs {ref}")
    if phantom:
        problems.append(f"{len(phantom)} committed key(s) the harness never wrote: {phantom[:20]}")
    if problems:
        raise InvariantViolation(f"[{label}] " + "\n  ".join(problems))
    return result


# ---------------------------------------------------------------- part A

def pct(sorted_vals, p):
    if not sorted_vals:
        return float("nan")
    k = (len(sorted_vals) - 1) * p / 100
    lo, hi = int(k), min(int(k) + 1, len(sorted_vals) - 1)
    return sorted_vals[lo] + (sorted_vals[hi] - sorted_vals[lo]) * (k - lo)


def part_a(cluster, args, timing):
    print(f"\n== Part A: failover time ({args.trials} trials, {cluster.size} nodes)")
    cluster.start_all()
    cluster.await_converged()
    failovers = []
    writers = []
    for trial in range(1, args.trials + 1):
        cluster.await_stable_leader(list(cluster.nodes), hold=0.5)
        cluster.await_converged()
        writer = Writer(cluster, f"a{trial}-k", timeout=args.request_timeout)
        writers.append(writer)
        thread = threading.Thread(target=writer.run, daemon=True)
        thread.start()
        try:
            # Steady writes first.
            t0 = time.monotonic()
            while len(writer.acked()) < 20:
                if time.monotonic() - t0 > 15 or not thread.is_alive():
                    raise HarnessError(f"trial {trial}: writes not flowing ({len(writer.acked())} acks)")
                time.sleep(0.01)
            got = cluster.agreed_leader(list(cluster.nodes))
            if not got:
                raise HarnessError(f"trial {trial}: no agreed leader before the kill")
            old_leader, old_term = got
            t_kill = time.monotonic()
            cluster.kill(old_leader)
            # First acknowledged write sent after the kill.
            rec = None
            while rec is None:
                if time.monotonic() - t_kill > 30 or not thread.is_alive():
                    raise HarnessError(f"trial {trial}: no write acknowledged within 30s of the kill")
                rec = next((r for r in writer.acked() if r.sent_at > t_kill), None)
                time.sleep(0.002)
        finally:
            writer.stop.set()
            thread.join(timeout=args.request_timeout + 5)
        survivors = [n for n in cluster.nodes if n != old_leader]
        new_leader, new_term = cluster.await_stable_leader(survivors, hold=0.2)
        if new_leader == old_leader or new_term <= old_term:
            raise HarnessError(f"trial {trial}: leadership did not change ({old_leader}@{old_term} -> "
                               f"{new_leader}@{new_term})")
        took = (rec.done_at - t_kill) * 1000
        failovers.append(took)
        print(f"  trial {trial:3d}: leader {old_leader} (term {old_term}) killed -> node {new_leader} "
              f"(term {new_term}); first ack {took:7.1f} ms after the kill "
              f"[{len(writer.ambiguous())} ambiguous in flight]")
        cluster.start(old_leader)  # revive; the next trial waits for convergence

    res = verify(cluster, writers, "part A")
    s = sorted(failovers)
    summary = {
        "trials": len(s), "min_ms": s[0], "p50_ms": pct(s, 50), "p90_ms": pct(s, 90),
        "p99_ms": pct(s, 99), "max_ms": s[-1], "mean_ms": statistics.mean(s),
        "acknowledged": res["acknowledged"], "ambiguous": res["ambiguous"], "lost": res["lost"],
    }
    print("\n-- Part A summary")
    if timing:
        print(f"  election timeout {timing[0]}-{timing[1]} ms (randomized), heartbeat {timing[2]} ms")
    print(f"  failover time over {len(s)} trials (leader SIGKILL -> first acknowledged write):")
    print(f"    min {s[0]:.1f}  p50 {pct(s, 50):.1f}  p90 {pct(s, 90):.1f}  p99 {pct(s, 99):.1f}  "
          f"max {s[-1]:.1f} ms  (mean {statistics.mean(s):.1f})")
    print(f"  writes: {res['acknowledged']} acknowledged, {res['ambiguous']} ambiguous "
          f"({res['ambiguous_present']} of them committed), {res['lost']} acknowledged lost; "
          f"committed logs identical on all {cluster.size} nodes (commit index {res['commit_index']})")
    return summary


# ---------------------------------------------------------------- part B

@dataclass
class ChaosStats:
    kills: int = 0
    freezes: int = 0
    minority_phases: int = 0
    minority_window: tuple = None   # (start, end) monotonic: a majority frozen
    log: list = field(default_factory=list)


def chaos_loop(cluster, args, stats, stop, rng):
    """Faults until `stop`: at most floor((N-1)/2) nodes faulty at once, so a
    majority can always make progress, plus (optionally) one bounded phase
    in which a majority is frozen and nothing may commit."""
    max_faulty = (cluster.size - 1) // 2
    faulty = {}  # nid -> (kind, heal_at)
    t_start = time.monotonic()
    minority_at = t_start + args.chaos_seconds * 0.5 if args.minority_phase else None

    def heal(nid):
        kind, _ = faulty.pop(nid)
        if kind == "kill":
            cluster.start(nid)
        else:
            cluster.thaw(nid)
        stats.log.append((time.monotonic() - t_start, f"heal {kind} n{nid}"))

    while not stop.is_set():
        now = time.monotonic()
        for nid, (kind, heal_at) in list(faulty.items()):
            if now >= heal_at:
                heal(nid)

        if minority_at is not None and now >= minority_at and not faulty:
            # Leave only the leader up: it can't reach a majority, so no
            # write sent from now until the heal may be acknowledged.
            got = cluster.agreed_leader(list(cluster.nodes))
            if got:  # else a node is still restarting: try again next round
                minority_at = None
                leader = got[0]
                others = [n for n in cluster.nodes if n != leader][:cluster.majority()]
                for nid in others:
                    cluster.freeze(nid)
                start = time.monotonic()
                stats.log.append((start - t_start, f"minority phase: froze {others}, leader n{leader} alone"))
                stop.wait(args.minority_seconds)
                end = time.monotonic()
                for nid in others:
                    cluster.thaw(nid)
                stats.minority_phases += 1
                stats.minority_window = (start, end)
                stats.log.append((end - t_start, "minority phase healed"))
                continue

        if len(faulty) < max_faulty and rng.random() < 0.5:
            candidates = [n for n in cluster.nodes if n not in faulty and cluster.healthy(n)]
            if candidates:
                nid = rng.choice(candidates)
                kind = rng.choice(["kill", "freeze"])
                if kind == "kill":
                    cluster.kill(nid)
                    stats.kills += 1
                else:
                    cluster.freeze(nid)
                    stats.freezes += 1
                faulty[nid] = (kind, now + rng.uniform(args.fault_min, args.fault_max))
                stats.log.append((time.monotonic() - t_start, f"{kind} n{nid}"))
        stop.wait(rng.uniform(0.2, 1.0))

    for nid in list(faulty):
        heal(nid)


def part_b(cluster, args):
    print(f"\n== Part B: chaos ({args.chaos_seconds}s, {cluster.size} nodes, {args.writers} writer(s), "
          f"at most {(cluster.size - 1) // 2} node(s) faulty at a time"
          f"{', plus a ' + str(args.minority_seconds) + 's majority-frozen phase' if args.minority_phase else ''})")
    cluster.start_all()
    cluster.await_converged()
    rng = random.Random(args.seed)
    writers = [Writer(cluster, f"b{w}-k", timeout=args.request_timeout) for w in range(args.writers)]
    threads = [threading.Thread(target=w.run, daemon=True) for w in writers]
    stats = ChaosStats()
    stop = threading.Event()
    chaos = threading.Thread(target=chaos_loop, args=(cluster, args, stats, stop, rng), daemon=True)
    for t in threads:
        t.start()
    chaos.start()
    t_end = time.monotonic() + args.chaos_seconds
    while time.monotonic() < t_end:
        if any(w.unexpected for w in writers):
            break
        time.sleep(0.2)
    stop.set()
    chaos.join()
    for w in writers:
        w.stop.set()
    for t in threads:
        t.join(timeout=args.request_timeout + 5)
    for w in writers:
        if w.unexpected:
            raise InvariantViolation(f"unexpected protocol reply: {w.unexpected[0]}")
    crashed = cluster.unexpected_exits()
    if crashed:
        raise InvariantViolation(f"node(s) exited on their own during chaos: {crashed}")

    for t, what in stats.log:
        if args.verbose:
            print(f"  t={t:6.2f}s  {what}")

    # Nothing sent while a majority was frozen may have been acknowledged.
    forbidden = []
    if stats.minority_window:
        s, e = stats.minority_window
        forbidden = [r for w in writers for r in w.acked() if r.sent_at > s and r.done_at < e]
        if forbidden:
            r = forbidden[0]
            raise InvariantViolation(f"{len(forbidden)} write(s) acknowledged while a majority was frozen, "
                                     f"e.g. {r.key}={r.value!r} ({r.detail})")

    res = verify(cluster, writers, "part B")
    attempts = sum(w.attempts for w in writers)
    faults = stats.kills + stats.freezes + stats.minority_phases
    print("\n-- Part B summary")
    print(f"  requests sent {attempts}, redirects followed {sum(w.redirects for w in writers)}, "
          f"not-acknowledged retries (ERR_NO_LEADER/refused) {sum(w.not_acked for w in writers)}")
    print(f"  faults injected: {stats.kills} kill+restart, {stats.freezes} freeze+thaw (SIGSTOP/SIGCONT)"
          f"{f', {stats.minority_phases} majority-frozen phase' if stats.minority_phases else ''}")
    if stats.minority_window:
        s, e = stats.minority_window
        sent = [r for w in writers for r in w.records if s < r.sent_at < e]
        if not sent:
            print("  WARNING: no write was sent during the majority-frozen phase, so it checked nothing; "
                  "raise --minority-seconds above --request-timeout")
        print(f"  majority-frozen phase ({e - s:.1f}s): {len(sent)} write(s) sent during it, "
              f"0 acknowledged before the heal")
    print(f"  writes: {res['acknowledged']} acknowledged, {res['ambiguous']} ambiguous "
          f"({res['ambiguous_present']} of them committed, never asserted)")
    print(f"  final: leader n{res['leader']} term {res['term']}, commit index {res['commit_index']} "
          f"on all {cluster.size} nodes; converged {res['converge_seconds']:.1f}s after chaos stopped")
    print(f"\n  RESULT: {res['acknowledged']} acknowledged writes, {res['lost']} lost, "
          f"{res['divergent_nodes']} divergence across {faults} injected faults")
    return {"acknowledged": res["acknowledged"], "ambiguous": res["ambiguous"], "lost": res["lost"],
            "divergence": res["divergent_nodes"], "kills": stats.kills, "freezes": stats.freezes,
            "minority_phases": stats.minority_phases, "faults": faults, "requests": attempts,
            "converge_seconds": res["converge_seconds"]}


